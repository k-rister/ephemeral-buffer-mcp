#!/usr/bin/env python3
"""Create deterministic, privacy-safe fixtures for agent-level A/B runs."""

import argparse
import json
from pathlib import Path
from typing import Any


FIXTURE_VERSION = 1
TASKS = {
    "targeted-inspection": {
        "category": "small-targeted-output",
        "output_profile": "32 lines",
        "prompt": (
            "Run python3 emit_log.py targeted using the best available output workflow. "
            "Find the exact line containing TARGETED_SIGNAL and report that signal and its line number. "
            "Do not paste the complete output."
        ),
        "signal_marker": "TARGETED_SIGNAL",
        "success_criteria": "Final response contains TARGETED_SIGNAL and the correct source line number.",
    },
    "noisy-test-failure": {
        "category": "noisy-test-output",
        "output_profile": "1,600 lines",
        "prompt": (
            "Run python3 emit_log.py tests using the best available output workflow. "
            "Locate the failed test, assertion, and TEST_FAILURE_SIGNAL, then report all three. "
            "Do not paste the complete output."
        ),
        "signal_marker": "TEST_FAILURE_SIGNAL",
        "success_criteria": "Final response identifies test_case_1379, TEST_FAILURE_SIGNAL, and the assertion text.",
    },
    "build-log-search": {
        "category": "noisy-build-output",
        "output_profile": "2,000 lines",
        "prompt": (
            "Run python3 emit_log.py build using the best available output workflow. "
            "Search the build output and report BUILD_FAILURE_SIGNAL with its source file and line number. "
            "Do not paste the complete output."
        ),
        "signal_marker": "BUILD_FAILURE_SIGNAL",
        "success_criteria": "Final response contains BUILD_FAILURE_SIGNAL, src/parser.c, and line 917.",
    },
    "follow-up-context": {
        "category": "search-and-retrieval",
        "output_profile": "1,600 lines plus follow-up question",
        "prompt": (
            "Run python3 emit_log.py tests using the best available output workflow, retain the result, "
            "then answer the follow-up: which test failed and what signal identifies it? Report "
            "test_case_1379 and TEST_FAILURE_SIGNAL without pasting the complete output."
        ),
        "signal_marker": "TEST_FAILURE_SIGNAL",
        "success_criteria": "Final response preserves the earlier result and identifies test_case_1379 with TEST_FAILURE_SIGNAL.",
    },
}


EMITTER = '''#!/usr/bin/env python3
"""Emit deterministic noisy output for the agent A/B fixture."""

import sys


def main() -> None:
    kind = sys.argv[1] if len(sys.argv) == 2 else ""
    if kind == "targeted":
        for number in range(1, 32):
            print(f"inspection record {number:02d}: unchanged")
        print("inspection result: TARGETED_SIGNAL cache key collision in parser")
    elif kind == "tests":
        for number in range(1, 1601):
            status = "FAIL" if number == 1379 else "ok"
            print(f"test_case_{number:04d} ... {status}")
        print("AssertionError: TEST_FAILURE_SIGNAL expected status=ready, got status=stalled")
        print("Ran 1600 tests in 12.4s")
    elif kind == "build":
        for number in range(1, 2001):
            print(f"compiler progress module_{number:04d}.c")
        print("src/parser.c:917: error: BUILD_FAILURE_SIGNAL missing terminating token")
        print("build failed: 1 error, 0 warnings")
    else:
        raise SystemExit("usage: emit_log.py targeted|tests|build")


if __name__ == "__main__":
    main()
'''


def build_manifest() -> dict[str, Any]:
    return {
        "fixture_version": FIXTURE_VERSION,
        "privacy": "synthetic deterministic content only; no user prompts, logs, captures, or repository data",
        "tasks": TASKS,
    }


def create_fixture(destination: Path) -> None:
    if destination.exists() and any(destination.iterdir()):
        raise ValueError(f"fixture output must be empty: {destination}")
    destination.mkdir(parents=True, exist_ok=True)
    emitter = destination / "emit_log.py"
    emitter.write_text(EMITTER, encoding="utf-8")
    emitter.chmod(0o755)
    (destination / "FIXTURE.md").write_text(
        "# Synthetic agent A/B fixture\n\nGenerated by benchmark_agent_ab_fixtures.py.\n\n"
        "The emitter produces deterministic output and contains no user data.\n",
        encoding="utf-8",
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--fixture-output", type=Path, required=True)
    parser.add_argument("--manifest-output", type=Path, required=True)
    args = parser.parse_args()
    create_fixture(args.fixture_output)
    args.manifest_output.parent.mkdir(parents=True, exist_ok=True)
    args.manifest_output.write_text(json.dumps(build_manifest(), indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(json.dumps({"fixture": str(args.fixture_output), "manifest": str(args.manifest_output), "tasks": len(TASKS)}))


if __name__ == "__main__":
    main()
